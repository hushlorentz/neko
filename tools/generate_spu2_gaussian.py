#!/usr/bin/env python3
"""Reconstruct SPU2 interpolation coefficients without importing emulator tables.

For half-integer x in [1/2, 1023/2], define
  c(x) = cos(2*pi*x/1023)
  K(x) = sin(pi*x/500) * (1+c(x)) * (17+8*c(x)) / (50*x).
Let S = 32640*128 / sum(K(x)) over those 512 points. For phase p=0..255,
the chronological tap positions are (p+256.5, p+0.5, 255.5-p, 511.5-p).
Each coefficient is round_even(8160 + S*(K(tap)-mean(K(taps)))).

This factored windowed-sinc reconstruction is derived from the mathematics
credited to nocash/Ryphecha/Near in the locally consulted PCSX2
c83f7bd88f27f10f865942d2fc38cc7695f250c5 pcsx2/SPU2/interpolate_table.h and
DobieStation 68dd073e751960fd01c839ac34ce6e056d70024a
src/core/iop/spu/spu_interpolate.cpp. Neither their code nor tables are imported.
The numerical reconstruction is secondary compatibility evidence, not a measured
SPU2 ROM dump. Matching derived tables are not independent hardware measurements.

Neko independently evaluates the factored equation with Decimal Taylor series
and Machin's pi identity, verifies 80/112-digit agreement, and emits integer
data. Regenerate with python3 -B tools/generate_spu2_gaussian.py; --check
verifies the committed header without modifying it.
"""

import argparse
from decimal import Context, Decimal, ROUND_HALF_EVEN, localcontext
from pathlib import Path
import sys


DEFAULT_OUTPUT = (
    Path(__file__).resolve().parents[1]
    / "neko" / "iop" / "spu2_gaussian_coefficients.hpp"
)


def _arctangent_reciprocal(divisor, epsilon):
    reciprocal = Decimal(1) / divisor
    power = reciprocal
    result = Decimal(0)
    for index in range(1024):
        term = power / (2 * index + 1)
        result += term
        if abs(term) < epsilon:
            return result
        power *= -(reciprocal * reciprocal)
    raise ArithmeticError("pi series did not converge")


def _sine_cosine(angle, pi, epsilon):
    angle = (angle + pi) % (2 * pi) - pi
    square = angle * angle
    sine = sine_term = angle
    cosine = cosine_term = Decimal(1)
    for index in range(1, 1024):
        sine_term *= -square / ((2 * index) * (2 * index + 1))
        cosine_term *= -square / ((2 * index - 1) * (2 * index))
        sine += sine_term
        cosine += cosine_term
        if max(abs(sine_term), abs(cosine_term)) < epsilon:
            return sine, cosine
    raise ArithmeticError("trigonometric series did not converge")


def calculate_coefficients(precision=80):
    if precision < 32:
        raise ValueError("coefficient calculation needs at least 32 digits")
    with localcontext(Context(prec=precision + 16, rounding=ROUND_HALF_EVEN)):
        epsilon = Decimal(10) ** (-precision - 8)
        pi = (
            16 * _arctangent_reciprocal(5, epsilon)
            - 4 * _arctangent_reciprocal(239, epsilon)
        )
        kernel = []
        for index in range(512):
            position = Decimal(2 * index + 1) / 2
            sine, _ = _sine_cosine(pi * position / 500, pi, epsilon)
            _, cosine = _sine_cosine(2 * pi * position / 1023, pi, epsilon)
            kernel.append(
                sine * (1 + cosine) * (17 + 8 * cosine) / (50 * position)
            )
        scale = Decimal(32640 * 128) / sum(kernel)
        rows = []
        for phase in range(256):
            taps = [kernel[index] for index in (
                phase + 256, phase, 255 - phase, 511 - phase,
            )]
            mean = sum(taps) / 4
            row = []
            for tap in taps:
                value = 8160 + scale * (tap - mean)
                nearest = value.to_integral_value(rounding=ROUND_HALF_EVEN)
                margin = Decimal("0.5") - abs(value - nearest)
                if margin <= epsilon * 1000000:
                    raise ArithmeticError("coefficient rounding is unresolved")
                coefficient = int(nearest)
                if not -32768 <= coefficient <= 32767:
                    raise ArithmeticError("coefficient exceeds signed16 range")
                row.append(coefficient)
            rows.append(tuple(row))
        return tuple(rows)


def render_header(rows):
    lines = [
        "// Generated by tools/generate_spu2_gaussian.py; do not edit.",
        "// Independently evaluated reconstruction; see generator for provenance.",
        "#ifndef SPU2_GAUSSIAN_COEFFICIENTS_HPP",
        "#define SPU2_GAUSSIAN_COEFFICIENTS_HPP",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace SPU2Gaussian",
        "{",
        "  constexpr std::array<std::array<std::int16_t, 4>, 256> coefficients = {{",
    ]
    lines.extend("    {{" + ", ".join(map(str, row)) + "}}," for row in rows)
    lines.extend(["  }};", "}", "", "#endif", ""])
    return "\n".join(lines).encode("ascii")


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--check", action="store_true", help="verify without writing")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    arguments = parser.parse_args(argv)
    rows = calculate_coefficients(80)
    if rows != calculate_coefficients(112):
        raise ArithmeticError("coefficient results disagree across precisions")
    expected = render_header(rows)
    if arguments.check:
        if not arguments.output.exists():
            print(f"missing generated coefficients: {arguments.output}", file=sys.stderr)
            return 1
        if arguments.output.read_bytes() != expected:
            print(f"generated coefficients differ: {arguments.output}", file=sys.stderr)
            return 1
    else:
        arguments.output.write_bytes(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main())
